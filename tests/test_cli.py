# Fixture helpers
# ---------------------------------------------------------------------


def _write_c08_config(
    config_dir: Path,
    config_name: str,
    data_relpath: str = "g27_1.txt",
) -> Path:
    """Write a c08-style defaults.txt that points at the bundled g27_1.txt.

    c08 = "no repeats" -- the smallest valid run.  Path is recorded
    relative to the config file's directory to exercise the FINAL-A
    relative-path rule (CLI resolves against config_dir, not CWD).
    """
    cfg = config_dir / config_name
    cfg.write_text(
        "# generated by test_cli.py\n"
        f"Data_File\t{data_relpath}\n"
        "Normalize_Data\tNormalize data\n"
        "Spot_IDs_included_in_the_data_file\ttrue\n"
        "Maximum_Number_of_Missing_Values\t0\n"
        "Minimum_Absolute_Log_Ratio_Expression\t0.8\n"
        "Change_should_be_based_on\tDifference From 0\n"
        "Minimum_Correlation_between_Repeats\t0.0\n"
        "Repeat_Data_Files(comma delimited list)\t\n"
        "Repeat_Data_is_from\tDifferent time periods\n"
        "Clustering_Method\tSTEM Clustering Method\n"
        "Maximum_Number_of_Model_Profiles\t50\n"
        "Maximum_Unit_Change_in_Model_Profiles_between_Time_Points\t2\n"
        "Maximum_Correlation\t1.0\n"
        "Maximum_Number_of_Candidate_Model_Profiles\t1000000\n"
        "Number_of_Permutations_per_Gene\t50\n"
        "Permutation_Test_Should_Permute_Time_Point_0\ttrue\n"
        "Significance_Level\t0.05\n"
        "Correction_Method\tBonferroni\n"
        "Clustering_Minimum_Correlation\t0.7\n"
        "Clustering_Minimum_Correlation_Percentile\t0.0\n",
        encoding="utf-8",
    )
    return cfg


def _bundle_g27_1(config_dir: Path) -> Path:
    """Copy tests/golden/data/g27_1.txt next to the test config.

    The CLI resolves relative Data_File against the config's own
    directory, so each test that exercises relative-path resolution
    needs the data next to its config.
    """
    src = Path(__file__).resolve().parent / "golden" / "data" / "g27_1.txt"
    dst = config_dir / "g27_1.txt"
    if not dst.exists():
        dst.write_bytes(src.read_bytes())
    return dst


