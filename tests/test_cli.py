def test_cli_entry_point_via_subprocess(tmp_path: Path) -> None:
    """``python -m pystemtc.cli`` must agree with the in-process main().

    FINAL-A A4 freezes ``[project.scripts] pystemtc = "pystemtc.cli:main"``.
    Without a built wheel we exercise ``python -m`` (the same function
    the entry point calls) so the test does not depend on pip install.
    """
    config_dir = tmp_path / "cfg"
    config_dir.mkdir()
    out_dir = tmp_path / "out"
    _bundle_g27_1(config_dir)
    cfg = _write_c08_config(config_dir, "c08_entry.txt")

    proc = subprocess.run(
        [sys.executable, "-m", "pystemtc.cli",
         "run", "--config", str(cfg), "--output", str(out_dir)],
        capture_output=True, text=True, env={**os.environ, "PYTHONIOENCODING": "utf-8"},
        cwd=str(tmp_path),
    )

    assert proc.returncode == 0, proc.stderr
    assert (out_dir / "c08_entry_genetable.txt").is_file()
    assert (out_dir / "c08_entry_profiletable.txt").is_file()
