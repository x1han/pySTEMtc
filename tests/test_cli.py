def test_cli_run_happy_path(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    config_dir = tmp_path / "cfg"
    config_dir.mkdir()
    out_dir = tmp_path / "out"
    _bundle_g27_1(config_dir)
    cfg = _write_c08_config(config_dir, "c08_run_ok.txt")

    rc = cli.main(["run", "--config", str(cfg), "--output", str(out_dir)])

    assert rc == 0
    out_lines = capsys.readouterr().out.strip().splitlines()
    # cmd_run prints the absolute paths of the two written tables
    assert len(out_lines) == 2
    assert out_lines[0].endswith("c08_run_ok_genetable.txt")
    assert out_lines[1].endswith("c08_run_ok_profiletable.txt")
    assert Path(out_lines[0]).is_file()
    assert Path(out_lines[1]).is_file()


def test_cli_run_resolves_relative_path_against_config_dir(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Even with a different CWD, the CLI must find Data_File via the config dir."""
    config_dir = tmp_path / "cfg"
    config_dir.mkdir()
    out_dir = tmp_path / "out"
    _bundle_g27_1(config_dir)
    cfg = _write_c08_config(config_dir, "c08_relpath.txt")

    other_cwd = tmp_path / "elsewhere"
    other_cwd.mkdir()
    monkeypatch.chdir(other_cwd)

    rc = cli.main(["run", "--config", str(cfg), "--output", str(out_dir)])

    assert rc == 0, capsys.readouterr().err
    assert (out_dir / "c08_relpath_genetable.txt").is_file()
    assert (out_dir / "c08_relpath_profiletable.txt").is_file()


