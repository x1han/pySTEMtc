"""CLI smoke tests for the FINAL-A A4 frozen surface.

Frozen commands:
    pystemtc run    --config <defaults.txt> --output <dir>
    pystemtc batch  --config-dir <dir>  --output <dir>

Frozen exit codes:
    0 = success
    1 = analysis / config / I/O failure (per-config in batch mode)
    2 = CLI usage error (bad args, missing --config / --output,
       config path does not exist, etc.)

These tests exercise the CLI through :func:`pystemtc.cli.main` (the
same function pyproject.toml's ``[project.scripts]`` entry points to)
and through ``subprocess`` for the entry-point script path -- the
latter is what :pep:`518` build backends and downstream packaging
will exercise.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

from pystemtc import cli


