def test_correct_fdr_walk_and_crash():
    # step-down walk: dthresh = last p_(i) < (i+1)*alpha/n; significant = p <= dthresh
    sig, pvals = correct([0.01, 0.5, 0.6], 0.1, "fdr")
    assert pvals == [0.01, 0.5, 0.6]
    assert sig == [True, False, False]  # dthresh = 0.01 (0.5 fails at i=1)
    sig2, _ = correct([0.5, 0.6, 0.7], 0.1, "fdr")
    assert sig2 == [False, False, False]  # dthresh stays 0
    # all-significant case: Java walks off pvalcopy[n] -> ArrayIndexOutOfBounds;
    # the port raises the equivalent IndexError and this is NOT fixed away
    with pytest.raises(IndexError):
        correct([0.01, 0.02, 0.03], 0.1, "fdr")


def test_correct_non_fdr_strict_and_count_rule():
    # Bonferroni: alpha/n; significant = p < threshold AND count > 1 (strict <)
    sig, _ = correct([0.005, 0.005], 0.05, "bonferroni", counts=[2.0, 1.0])
    assert sig == [True, False]  # equal threshold: strict < rejects count==1 row
    # count == threshold boundary: p == alpha/n is NOT significant (strict <)
    sig2, _ = correct([0.025, 0.024], 0.05, "bonferroni", counts=[3.0, 3.0])
    assert sig2 == [False, True]
    # none: plain alpha with the same strict < and count rule
    sig3, _ = correct([0.0499999, 0.05, 0.005], 0.05, "none", counts=[5.0, 5.0, 1.0])
    assert sig3 == [True, False, False]


