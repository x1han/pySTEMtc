def test_enumerate_candidates_count_and_order():
    # (u=1, T=3): 3^2 = 9 candidates, the all-zero one removed -> 8
    c13 = enumerate_candidates(1, 3)
    assert len(c13) == 8
    # last column varies fastest; steps (i//3, i%3) - 1; original index 4 is zero
    assert c13[0] == [0.0, -1.0, -2.0]
    assert c13[1] == [0.0, -1.0, -1.0]
    assert c13[2] == [0.0, -1.0, 0.0]
    assert c13[3] == [0.0, 0.0, -1.0]
    assert c13[4] == [0.0, 0.0, 1.0]  # original index 5 (zero row removed)
    assert c13[7] == [0.0, 1.0, 2.0]

    # (u=2, T=4): 5^3 = 125 -> 124
    c24 = enumerate_candidates(2, 4)
    assert len(c24) == 124
    assert all(row[0] == 0.0 for row in c24)
    assert not any(all(v == 0.0 for v in row) for row in c24)


def test_compact_seed_is_monotone_profile():
    # :1582-1587 — the seed index equals the candidate index of the unit-step
    # monotone profile {0, 1, ..., T-1} for every u; the seed is the FIRST
    # selected candidate (selectedindex[0]) and therefore always among the
    # compacted profiles
    for u, T in ((1, 3), (1, 5), (2, 4), (2, 6)):
        cands = enumerate_candidates(u, T)
        models, ids = _compact_profiles2_scalar(cands, 50, 1.0, u)
        assert ids == sorted(ids)
        monotone = [float(i) for i in range(T)]
        assert monotone in models, (u, T)


def test_compact_bulk_and_scalar_agree():
    for u, T in ((1, 5), (2, 4), (2, 6)):
        cands = enumerate_candidates(u, T)
        ms, ids_s = _compact_profiles2_scalar(cands, 50, 1.0, u)
        mb, ids_b = _compact_profiles2_bulk(cands, 50, 1.0, u)
        assert ms == mb and ids_s == ids_b
    # also on a random-walk sample (includes constant candidates -> NaN paths)
    cands = sample_candidates(2, 5, 2000)
    ms, ids_s = _compact_profiles2_scalar(cands, 20, 1.0, 2)
    mb, ids_b = _compact_profiles2_bulk(cands, 20, 1.0, 2)
    assert ms == mb and ids_s == ids_b


def test_sample_candidates():
    # sample 0 is the strictly descending profile and consumes no RNG
    s = sample_candidates(2, 5, 4)
    assert s[0] == [0.0, -2.0, -4.0, -6.0, -8.0]
    # rows 1.. reproduce Random(3733246) walks step by step
    rng = JavaRandom(3733246)
    for nsample in (1, 2, 3):
        value = 0.0
        row = [0.0]
        for _ in range(4):
            value = value + math.floor(rng.next_double() * 5 - 2)
            row.append(float(value))
        assert s[nsample] == row
    # cap == 1: no RNG consumed at all
    assert sample_candidates(1, 3, 1) == [[0.0, -1.0, -2.0]]


