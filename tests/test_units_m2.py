_A = [0.0, 1.0, 2.0, 3.0]
_B = [0.0, -3.0, 0.0, 3.0]
_C = [0.0, 0.0, 3.0, 2.0]


def test_cluster_member_rule_is_ge_threshold():
    # corr(A,B) = 0.6324..., corr(A,C) = 0.7745..., corr(B,C) = 0.5443...
    t_bc = correlation(_B, _C, [1, 1, 1, 1], [1, 1, 1, 1])
    t_ab = correlation(_A, _B, [1, 1, 1, 1], [1, 1, 1, 1])
    t_ac = correlation(_A, _C, [1, 1, 1, 1], [1, 1, 1, 1])
    assert t_ab > t_bc and t_ac > t_bc
    models = [_A, _B, _C]
    counts = [1.0, 1.0, 1.0]
    # thr == corr(B,C) exactly: B is a candidate for A's ball (t_ab > thr),
    # and as a ball member corr(B, C) == thr satisfies the >= member rule
    # (closeToAllNeighbors rejects only corr < thr), so one 3-profile cluster
    clusters = cluster_profiles([0, 1, 2], counts, models, t_bc, 0.0)
    assert clusters == [[0, 2, 1]]


def test_cluster_neighbor_rule_is_strict_gt_and_center_dist_quirk():
    # X and Y have correlation exactly 1.0
    x = [0.0, 1.0, 2.0, 3.0]
    y = [0.0, 2.0, 4.0, 6.0]
    t = correlation(x, y, [1, 1, 1, 1], [1, 1, 1, 1])
    assert t == 1.0
    counts = [2.0, 3.0]
    # thr == corr: neighbors need corr > thr -> no candidates; each center's
    # ball is itself, and Y (count 3) wins the first round (strict >)
    clusters = cluster_profiles([0, 1], counts, [x, y], t, 0.0)
    assert clusters == [[1], [0]]
    # thr slightly below: Y is a candidate of X's ball; the center X is added
    # with distance 1.0 which the TreeSet REJECTS (equal to Y's distance), so
    # the best ball is [Y] only (X not removed) and X clusters afterwards
    clusters2 = cluster_profiles([0, 1], counts, [x, y], t - 1e-9, 0.0)
    assert clusters2 == [[1], [0]]


