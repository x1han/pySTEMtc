def _java_float(text: str) -> float:
    """Parse a Java-printed double literal ('1.0E-9', '4.5E-17', ...)."""
    return float(text.replace("E", "e"))


def test_statutil_binomialtail_golden_vectors():
    lines = VECTORS.read_text(encoding="utf-8").splitlines()
    assert len(lines) > 100
    checked = 0
    for line in lines:
        parts = line.split("\t")
        if parts[0] == "BINOMTAIL":
            x, n = int(parts[1]), int(parts[2])
            dp = _java_float(parts[3])
            want = _java_float(parts[4])
            got = binomial_tail(x, n, dp)
            assert got == want, f"binomialtail({x},{n},{dp}): {got} != {want}"
            checked += 1
        elif parts[0] == "LOGBINOM":
            ni, n = int(parts[1]), int(parts[2])
            want = _java_float(parts[3])
            got = logbinomcoeff(ni, n)
            assert got == want, f"logbinomcoeff({ni},{n}): {got} != {want}"
            checked += 1
    assert checked == len(lines)


def test_binomialtail_boundary_semantics():
    # x > N -> 0 (checked before the x++ quirk)
    assert binomial_tail(60, 10, 0.3) == 0.0
    # x < 0 (count 0: ceil(-1) = -1) -> 1
    assert binomial_tail(-1, 10, 0.3) == 1.0
    # dp <= 0 / dp >= 1 -> 1 (dp == 1 also returns 1)
    assert binomial_tail(5, 50, 0.0) == 1.0
    assert binomial_tail(5, 50, 1.0) == 1.0
    # x_orig == N quirk: x++ enters the formula producing a tiny nonzero value
    assert binomial_tail(10, 10, 0.3) == _java_float("0.0000025306714285714307")
    # interior value pinned by jjs
    assert binomial_tail(2, 10, 0.3) == _java_float("0.6172172135999991")
    # 0 < count < 1 and count == 1 both cast to x=0, then x++ -> P(X >= 1)
    from pystemtc.significance import count_pvalue
    assert count_pvalue(0.5, 10, 0.3) == count_pvalue(1.0, 10, 0.3)
    assert count_pvalue(0.5, 10, 0.3) == binomial_tail(0, 10, 0.3)


