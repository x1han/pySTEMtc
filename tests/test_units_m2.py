def test_expected_counts_meta_modes():
    # T=4 -> exact path with n=0 and with n >= 4!
    ds = _toy_dataset()
    models = [[0.0, 1.0, 2.0, 3.0], [0.0, -1.0, -2.0, -3.0]]
    expected, meta = expected_counts(ds, models, 0, True)
    assert meta["permutation_mode"] == "exact"
    assert meta["legacy_with_replacement"] is False
    assert meta["n_permutations_requested"] == 0
    # scaling: expected * numrows / ntotalassignments
    numrows = ds.gene_data.shape[0]
    assert all(0.0 <= v <= numrows + 1e-9 for v in expected)
    # t0 fixed: (T-1)! = 6 universe, requesting 2 -> legacy subsample path
    _, meta2 = expected_counts(ds, models, 2, False)
    assert meta2["permutation_mode"] == "subsample_universe"
    assert meta2["legacy_with_replacement"] is True
    # on-the-fly needs T >= 9: emulate via a 10-column dataset
    rng = np.random.default_rng(7)
    data = rng.normal(size=(6, 10))
    pma = np.full((6, 10), 2, dtype=np.int8)
    main = SpotSet(
        raw_data=data,
        raw_pma=pma,
        spot_ids=[f"S{i}" for i in range(6)],
        gene_ids=[f"G{i}" for i in range(6)],
        probe_ids=[f"S{i}" for i in range(6)],
        sample_labels=[str(i) for i in range(10)],
    )
    cfg = STEMConfig(normalize="none_add0", min_abs_expr=0.0, maxmin=False)
    ds10 = build_stem_dataset(main, [], "different_periods", cfg)
    models10 = [[float(i % 3 - 1) for i in range(10)]]
    _, meta3 = expected_counts(ds10, models10, 5, True)
    assert meta3["permutation_mode"] == "on_the_fly"


