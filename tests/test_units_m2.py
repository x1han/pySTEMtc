def test_double_to_sz():
    assert double_to_sz(0.0) == "0.00"
    assert double_to_sz(-1.0) == "0.00"  # dval <= 0 -> "0.00"
    assert double_to_sz(1.0) == "1.00"
    assert double_to_sz(0.5) == "0.50"
    assert double_to_sz(0.38) == "0.38"
    assert double_to_sz(0.995) == "0.99"  # 0.995 binary < 0.995 decimal
    # scaling branch boundary: nexp == -2 stays plain, -3 goes scientific
    assert double_to_sz(0.0095) == "9.5E-3"
    assert double_to_sz(0.01) == "0.01"
    # small values: mantissa recomputed via Math.pow(10, log10(d)-nexp)
    assert double_to_sz(7.1e-7) == "7.1E-7"
    assert double_to_sz(1.0) == "1.00"


